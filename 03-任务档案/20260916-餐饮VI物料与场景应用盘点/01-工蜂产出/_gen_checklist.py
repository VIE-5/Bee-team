def validate():
    problems, used = [], {}
    for sec in SECTIONS:
        for name, code, qty, note in sec["rows"]:
            if code:
                if code not in CODE:
                    problems.append(f"未知码：{code}（{name}）")
                used[code] = used.get(code, 0) + 1
    missing = [k for k in CODE if k not in used]
    if missing:
        problems.append(f"码表未被清单覆盖：{', '.join(missing)}")
    return problems, used


def stats():
    total = sum(len(s["rows"]) for s in SECTIONS)
    material = sum(1 for s in SECTIONS for r in s["rows"] if r[1].startswith("M"))
    scene = sum(1 for s in SECTIONS for r in s["rows"] if r[1].startswith("S"))
    base = sum(1 for s in SECTIONS for r in s["rows"] if not r[1])
    by_act = {}
    for s in SECTIONS:
        for r in s["rows"]:
            if r[1]:
                act = CODE[r[1]]["act"]
                by_act[act] = by_act.get(act, 0) + 1
    return total, material, scene, base, by_act


def cell(code, key):
    """从码表取三源数值，基座项返回 —"""
    if not code:
        return "—"
    return f'{CODE[code][key]:.1f}%'


def row_line(idx, name, code, qty, note):
    if code:
        v, act = CODE[code]["verdict"], CODE[code]["act"]
        cinfo = f'**{code}**'
    else:
        v, act, cinfo = "基座", "前置必备", "—"
    return f'| {idx} | {name} | {cinfo} | {qty} | {cell(code,"a")} | {cell(code,"b")} | {cell(code,"c")} | {v} | {act} |'


